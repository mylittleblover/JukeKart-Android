"""Generate exact confirmed source-frame mappings; suffixes enumerate points, not audio files."""
import argparse
from collections import defaultdict
from pathlib import Path
import re


def generate(text):
    stages = {}
    current = None
    for line in text.splitlines():
        header = re.fullmatch(r'## (\w+) \([\d.]+ BPM\)', line)
        if header:
            current = defaultdict(list)
            if header[1] in stages:
                raise ValueError('duplicate stage: ' + header[1])
            stages[header[1]] = current
        elif line.startswith('| Outro') and not line.startswith('| Outro |'):
            match = re.fullmatch(r'\| Outro(\d+)(?:_\d+)? \| [\d:.]+ \| (\d+) \|', line)
            if current is None or match is None:
                raise ValueError('malformed trigger: ' + line)
            current[int(match[1])].append(int(match[2]))
    if not stages or any(not points for points in stages.values()):
        raise ValueError('empty trigger table')
    lines = ['package com.mylittleblover.mkwplayer.interactive', '',
             '// Generated by tools/gen_confirmed_outros.py from the user-confirmed table.',
             '// Coordinates are Full SOURCE frames at 48 kHz, not Transport or Outro lengths.',
             'internal object ConfirmedOutroCatalog {',
             '    fun forStage(stage: String): Map<Int, List<Long>>? = stages[stage]',
             '    private val stages: Map<String, Map<Int, List<Long>>> = mapOf(']
    for stage, outros in stages.items():
        lines.append(f'        "{stage}" to mapOf(')
        for number, frames in sorted(outros.items()):
            if len(set(frames)) != len(frames):
                raise ValueError('duplicate source frame')
            lines.append(f'            {number} to listOf(' + ', '.join(str(n)+'L' for n in sorted(frames)) + '),')
        lines.append('        ),')
    lines += ['    )', '}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('source', type=Path)
    ap.add_argument('output', type=Path)
    args = ap.parse_args()
    args.output.write_text(generate(args.source.read_text()), encoding='utf-8')
